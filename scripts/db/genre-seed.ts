/**
 * Generates the migration that seeds public.genre_similarity and
 * public.genre_alias from the genre artifact (table.json) and CANON_MAP, so
 * the SQL preview ranking scores genres from the same data as the TypeScript
 * matcher.
 *
 *   bun scripts/db/genre-seed.ts
 *
 * Writes supabase/migrations/<timestamp>_seed_genre_similarity_v<version>.sql,
 * or does nothing when the latest committed seed already matches. Rerun it
 * after syncing a new table.json or editing CANON_MAP;
 * scripts/__tests__/genre-seed.test.ts fails until you do.
 */

import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { GENRE_TABLE_VERSION } from "@/lib/domains/taste/genre-similarity/loader";
import rawTable from "@/lib/domains/taste/genre-similarity/table.json";
import { CANON_MAP } from "@/lib/integrations/lastfm/whitelist";

export const MIGRATIONS_DIR = join(
	import.meta.dirname,
	"..",
	"..",
	"supabase",
	"migrations",
);

const SEED_FILE_PATTERN = /^\d{14}_seed_genre_similarity_v[\w]+\.sql$/;

function quote(value: string): string {
	return `'${value.replaceAll("'", "''")}'`;
}

// Code-unit order, not locale order, so the output is byte-stable across
// machines.
function byCodeUnit(a: string, b: string): number {
	if (a < b) return -1;
	return a > b ? 1 : 0;
}

function renderData(): string {
	const table = rawTable as unknown as Record<string, Record<string, number>>;
	const edges: string[] = [];
	for (const from of Object.keys(table).filter((k) => k !== "_meta").sort(byCodeUnit)) {
		for (const to of Object.keys(table[from]).sort(byCodeUnit)) {
			// String(number) is the shortest round-trip form, so Postgres parses
			// the literal to the same double the TypeScript scorer reads.
			edges.push(`(${quote(from)}, ${quote(to)}, ${String(table[from][to])})`);
		}
	}

	const aliases = [...CANON_MAP.entries()]
		.sort(([a], [b]) => byCodeUnit(a, b))
		.map(([alias, canonical]) => `(${quote(alias)}, ${quote(canonical)})`);

	return [
		"DELETE FROM public.genre_similarity;",
		"DELETE FROM public.genre_alias;",
		"",
		"INSERT INTO public.genre_similarity (from_genre, to_genre, similarity) VALUES",
		`${edges.join(",\n")};`,
		"",
		"INSERT INTO public.genre_alias (alias, canonical) VALUES",
		`${aliases.join(",\n")};`,
	].join("\n");
}

/** The full seed migration for the current table.json + CANON_MAP. */
export function renderGenreSeedSql(): string {
	const data = renderData();
	const hash = createHash("sha256").update(data).digest("hex");
	const marker = `GENRE_TABLE_VERSION ${GENRE_TABLE_VERSION}, content sha256 ${hash}`;
	return [
		"-- Generated by scripts/db/genre-seed.ts from",
		"-- src/lib/domains/taste/genre-similarity/table.json and CANON_MAP in",
		"-- src/lib/integrations/lastfm/whitelist.ts. Do not edit; rerun the script.",
		`-- ${marker}`,
		"--",
		"-- Replaces the whole data set inside this migration's transaction: the rows",
		"-- are derived reference data with no other writer, and a pair dropped from",
		"-- table.json must disappear here too or the SQL ranking keeps crediting it.",
		"",
		data,
		"",
		`COMMENT ON TABLE public.genre_similarity IS ${quote(marker)};`,
		"",
	].join("\n");
}

/** The newest committed seed migration, or null when none exists yet. */
export function latestGenreSeedMigration(): {
	name: string;
	sql: string;
} | null {
	const name = readdirSync(MIGRATIONS_DIR)
		.filter((f) => SEED_FILE_PATTERN.test(f))
		.sort()
		.at(-1);
	if (!name) return null;
	return { name, sql: readFileSync(join(MIGRATIONS_DIR, name), "utf8") };
}

function utcTimestamp(date: Date): string {
	return date.toISOString().replace(/\D/g, "").slice(0, 14);
}

function parseTimestamp(ts: string): Date {
	return new Date(
		`${ts.slice(0, 4)}-${ts.slice(4, 6)}-${ts.slice(6, 8)}T${ts.slice(8, 10)}:${ts.slice(10, 12)}:${ts.slice(12, 14)}Z`,
	);
}

// Hand-numbered migrations often carry timestamps ahead of the clock, and
// `supabase db push` refuses a file older than the newest applied one.
function nextMigrationTimestamp(now: Date): string {
	const newest = readdirSync(MIGRATIONS_DIR)
		.map((f) => f.slice(0, 14))
		.filter((ts) => /^\d{14}$/.test(ts))
		.sort()
		.at(-1);
	if (!newest) return utcTimestamp(now);
	const afterNewest = new Date(parseTimestamp(newest).getTime() + 60_000);
	return utcTimestamp(afterNewest > now ? afterNewest : now);
}

if (import.meta.main) {
	const rendered = renderGenreSeedSql();
	const latest = latestGenreSeedMigration();
	if (latest?.sql === rendered) {
		console.log(`${latest.name} already matches table.json; nothing to do.`);
	} else {
		const version = GENRE_TABLE_VERSION.replace(/\W/g, "_");
		const name = `${nextMigrationTimestamp(new Date())}_seed_genre_similarity_v${version}.sql`;
		writeFileSync(join(MIGRATIONS_DIR, name), rendered);
		console.log(`Wrote supabase/migrations/${name}`);
	}
}
